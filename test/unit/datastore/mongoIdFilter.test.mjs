// _id normalisation in the Mongo adapter.
//
// In unified-DB mode every stored _id is prefixed `<owner>__<appTable>__`. The adapter
// used to add that prefix only for a bare string `_id`; `{ _id: { $in: [...] } }` and
// `$or` of ids reached Mongo unprefixed and matched nothing - and were also treated as
// a single-record lookup (findOne). NeDB has no prefixes, so apps that worked on
// localhost silently broke on a unified Mongo install (Orbit's published-file badges
// query `files` with `_id: { $in: [...] }`).

import { expect } from 'chai'
import { ObjectId } from 'mongodb'
import MONGO_FOR_FREEZR, { __idFilterInternals } from '../../../adapters/datastore/dbConnectors/dbApi_mongodb.mjs'

const { normalizeIdFilter } = __idFilterInternals

const store = (strategy) => new MONGO_FOR_FREEZR(
  {
    dbParams: {
      choice: 'mongoString',
      type: 'mongodb',
      mongoString: 'mongodb://u:p@host:27017/?ssl=true',
      dbUnificationStrategy: strategy,
      useUserIdsAsDbName: true
    },
    fsParams: { type: 'local' }
  },
  { owner: 'sfweb', app_table: 'com.salmanff.orbit.files' }
)

const PREFIX = 'sfweb__com_salmanff_orbit_files__'

describe('mongo adapter _id filter normalisation', function () {
  describe("unified strategy ('all')", function () {
    const self = store('all')

    it('prefixes a bare string id and marks it single', function () {
      const { filter, single } = normalizeIdFilter(self, 'projects/p/public/a.html')
      expect(filter).to.deep.equal({ _id: PREFIX + 'projects/p/public/a.html' })
      expect(single).to.equal(true)
    })

    it('prefixes a string _id inside a query object and marks it single', function () {
      const { filter, single } = normalizeIdFilter(self, { _id: 'projects/p/public/a.html', x: 1 })
      expect(filter).to.deep.equal({ _id: PREFIX + 'projects/p/public/a.html', x: 1 })
      expect(single).to.equal(true)
    })

    it('prefixes every element of _id $in and is NOT single', function () {
      const { filter, single } = normalizeIdFilter(self, { _id: { $in: ['a.html', 'b.html'] } })
      expect(filter).to.deep.equal({ _id: { $in: [PREFIX + 'a.html', PREFIX + 'b.html'] } })
      expect(single, 'a $in must go through find, not findOne').to.equal(false)
    })

    it('handles $nin, $eq and $ne on _id', function () {
      const { filter } = normalizeIdFilter(self, { _id: { $nin: ['a'], $ne: 'b' } })
      expect(filter._id).to.deep.equal({ $nin: [PREFIX + 'a'], $ne: PREFIX + 'b' })
      expect(normalizeIdFilter(self, { _id: { $eq: 'c' } }).filter._id).to.deep.equal({ $eq: PREFIX + 'c' })
    })

    it('recurses into $or / $and clauses', function () {
      const { filter, single } = normalizeIdFilter(self, {
        $or: [{ _id: 'a' }, { _id: { $in: ['b', 'c'] } }, { name: 'untouched' }]
      })
      expect(filter.$or).to.deep.equal([
        { _id: PREFIX + 'a' },
        { _id: { $in: [PREFIX + 'b', PREFIX + 'c'] } },
        { name: 'untouched' }
      ])
      expect(single).to.equal(false)
    })

    it('does not double-prefix an id that already carries the prefix', function () {
      const { filter } = normalizeIdFilter(self, { _id: { $in: [PREFIX + 'a', 'b'] } })
      expect(filter._id.$in).to.deep.equal([PREFIX + 'a', PREFIX + 'b'])
    })

    it('leaves an autogenerated ObjectId alone and marks it single', function () {
      const oid = new ObjectId()
      expect(normalizeIdFilter(self, oid)).to.deep.equal({ filter: { _id: oid }, single: true })
      const hex = oid.toHexString()
      const { filter, single } = normalizeIdFilter(self, { _id: hex })
      expect(filter._id).to.be.instanceOf(ObjectId)
      expect(filter._id.toHexString()).to.equal(hex)
      expect(single).to.equal(true)
    })

    it('does not mutate the caller query (the cache keys on it)', function () {
      const q = { _id: { $in: ['a'] }, $or: [{ _id: 'b' }] }
      const snapshot = JSON.parse(JSON.stringify(q))
      normalizeIdFilter(self, q)
      expect(q).to.deep.equal(snapshot)
    })

    it('treats an empty / missing query as find-many', function () {
      expect(normalizeIdFilter(self, null)).to.deep.equal({ filter: {}, single: false })
      expect(normalizeIdFilter(self, { name: 'x' })).to.deep.equal({ filter: { name: 'x' }, single: false })
    })
  })

  describe("per-user databases ('db' strategy, no prefix)", function () {
    const self = store('db')

    it('leaves string ids as they are but still reports single correctly', function () {
      expect(normalizeIdFilter(self, 'a.html')).to.deep.equal({ filter: { _id: 'a.html' }, single: true })
      const { filter, single } = normalizeIdFilter(self, { _id: { $in: ['a.html', 'b.html'] } })
      expect(filter).to.deep.equal({ _id: { $in: ['a.html', 'b.html'] } })
      expect(single).to.equal(false)
    })
  })
})
